import type { ProjectDesignContract } from "./project-design-contract";

function list(values: string[]) {
  return values.length ? values.map((value) => `- ${value}`).join("\n") : "- None";
}

export function renderProjectDesignMd(contract: ProjectDesignContract) {
  const colors = Object.entries(contract.colors).map(([role, value]) => `- **${role}:** ${value.value} (${value.origin}; ${value.status})`);
  const references = contract.references.length
    ? contract.references.map((reference) => `- **${reference.name}:** ${reference.role}${reference.target ? ` for ${reference.target}` : ""}; ${reference.fidelity}; ${reference.scope}`)
    : ["- Original direction; no named external reference controls the project."];
  return [
    "# Project Design Contract",
    "",
    "Canonical portable design direction generated by Hassali.ai. This file is project guidance, not execution or approval authority.",
    "",
    `version: ${contract.version}`,
    `status: ${contract.status}`,
    `fingerprint: ${contract.fingerprint}`,
    `previousFingerprint: ${contract.previousFingerprint ?? "none"}`,
    `userBrand: ${contract.identity.userBrand}`,
    `archetype: ${contract.identity.archetype}`,
    `fidelity: ${contract.fidelity.mode}`,
    "authority: untrusted-design-data-only",
    "",
    "## Identity & Intent",
    "",
    `- Brand: ${contract.identity.userBrand}`,
    `- Original design: ${contract.identity.original ? "yes" : "no"}`,
    `- Purpose: ${contract.intent.purpose}`,
    `- Audience: ${contract.intent.audience}`,
    `- Personality: ${contract.intent.personality.join(", ")}`,
    "",
    "## Reference Composition",
    "",
    ...references,
    "",
    "## Semantic Colors",
    "",
    ...colors,
    "",
    "## Typography",
    "",
    `- Display: ${contract.typography.display}`,
    `- Body: ${contract.typography.body}`,
    `- Labels: ${contract.typography.labels}`,
    `- Line height: ${contract.typography.lineHeight}`,
    `- Responsive scale: h1 ${contract.typography.scale.h1}; h2 ${contract.typography.scale.h2}; body ${contract.typography.scale.body}`,
    `- Font policy: ${contract.typography.fallbackPolicy}`,
    "",
    "## Spacing & Layout",
    "",
    `- Scale: ${contract.spacing.scale.join(", ")}`,
    `- Page gutter: ${contract.spacing.pageGutter}`,
    `- Section gap: ${contract.spacing.sectionGap}`,
    `- Container: ${contract.layout.container}`,
    `- Grid: ${contract.layout.grid}`,
    `- Hero: ${contract.layout.hero}`,
    `- Rhythm: ${contract.layout.sectionRhythm.join(" -> ")}`,
    "",
    "## Geometry & Surfaces",
    "",
    `- Card radius: ${contract.geometry.cardRadius}`,
    `- Button radius: ${contract.geometry.buttonRadius}`,
    `- Borders: ${contract.geometry.borders}`,
    `- Image masks: ${contract.geometry.imageMask}`,
    `- Surfaces: ${contract.geometry.surfaceTreatment}`,
    "",
    "## Component Language",
    "",
    `- Navigation: ${contract.components.navigation}`,
    `- Buttons: ${contract.components.buttons}`,
    `- Cards: ${contract.components.cards}`,
    `- Forms: ${contract.components.forms}`,
    `- Footer: ${contract.components.footer}`,
    ...Object.entries(contract.components.sectionSpecific).map(([scope, rule]) => `- ${scope}: ${rule}`),
    "",
    "## Imagery & Motion",
    "",
    `- Imagery: ${contract.imagery.direction}`,
    `- Crop: ${contract.imagery.crop}`,
    `- Density: ${contract.imagery.density}`,
    `- Provenance: ${contract.imagery.provenancePolicy}`,
    `- Motion personality: ${contract.motion.personality}`,
    `- Motion evidence: ${contract.motion.evidence}`,
    `- Timing: ${contract.motion.timing}`,
    `- Reduced motion: ${contract.accessibility.reducedMotion}`,
    "",
    "## Responsive & Accessibility",
    "",
    `- Responsive evidence: ${contract.responsive.evidence}`,
    "- Desktop:",
    list(contract.responsive.desktop),
    "- Tablet:",
    list(contract.responsive.tablet),
    "- Mobile:",
    list(contract.responsive.mobile),
    `- Contrast: ${contract.accessibility.contrast}`,
    `- Focus: ${contract.accessibility.focus}`,
    `- Semantics: ${contract.accessibility.semantics}`,
    `- Touch: ${contract.accessibility.touchTargets}`,
    "",
    "## Content Hierarchy",
    "",
    `- Primary: ${contract.contentHierarchy.primaryMessage}`,
    `- Supporting: ${contract.contentHierarchy.supportingMessage}`,
    `- Reading order: ${contract.contentHierarchy.readingOrder}`,
    `- Long-copy width: ${contract.contentHierarchy.bodyWidth}`,
    "",
    "## Do",
    "",
    list(contract.doRules),
    "",
    "## Don't",
    "",
    list(contract.dontRules),
    "",
    "## Fidelity & Provenance",
    "",
    `- ${contract.fidelity.summary}`,
    ...contract.provenance.map((source) => `- ${source.label}: ${source.role}; ${source.status}; ${source.private ? "private" : "public"}`),
    "",
    "## Conflict Decisions",
    "",
    list(contract.conflicts.map((conflict) => `${conflict.dimension} [${conflict.severity}]: ${conflict.resolution}`)),
    "",
    "## Unresolved",
    "",
    list(contract.unresolved),
    ""
  ].join("\n").slice(0, 28_000);
}
